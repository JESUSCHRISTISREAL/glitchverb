    inline const Glyph* find (char c)
    {
        for (auto& g : glyphs)
            if (g.character == c)
                return &g;
        return nullptr;
    }

    // a small dot matrix window: faint unlit dots across it and the text centred on the grid,
    // lit with a little glow. pitch is the dot spacing. the dots are round and always keep
    // most of a screen pixel between them, so they stay separate at small window sizes
    inline void drawWindow (Graphics& g, Rectangle<float> area, const String& text, float pitch, Colour lit)
    {
        const int columns = (int) (area.getWidth() / pitch);
        const int rows = (int) (area.getHeight() / pitch);
        const float x0 = area.getX() + (area.getWidth() - pitch * (float) columns) * 0.5f;
        const float y0 = area.getY() + (area.getHeight() - pitch * (float) rows) * 0.5f;

        const float pixel = 1.0f / jmax (0.1f, g.getInternalContext().getPhysicalPixelScaleFactor());
        const float size = jmax (pixel, jmin (pitch * 0.62f, pitch - pixel * 0.9f));
        auto dot = [&] (int column, int row)
        {
            return Rectangle<float> (size, size).withCentre ({ x0 + pitch * ((float) column + 0.5f), y0 + pitch * ((float) row + 0.5f) });
        };

        Path unlit;
        for (int row = 0; row < rows; ++row)
            for (int column = 0; column < columns; ++column)
                unlit.addEllipse (dot (column, row));
        g.setColour (lit.withAlpha (0.07f));
        g.fillPath (unlit);

        Path on;
        int x = (columns - (text.length() * 6 - 1)) / 2;
        const int top = (rows - 7) / 2;
        for (auto c : text)
        {
            if (auto* glyph = find ((char) c))
                for (int row = 0; row < 7; ++row)
                    for (int column = 0; column < 5; ++column)
                        if (glyph->rows[row][column] == '#' && x + column >= 0 && x + column < columns)
                            on.addEllipse (dot (x + column, top + row));
            x += 6;
        }

        g.setColour (lit);
        g.fillPath (on);
    }
